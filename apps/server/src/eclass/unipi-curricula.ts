/**
 * Undergraduate curricula of the UniPi departments whose eClass catalog is one flat folder
 * (no semester sub-folders), so the semester has to come from the official study guide.
 *
 * Sources (checked 2026-11-19):
 *  - ode:  ode.unipi.gr studyguide_2025-26.pdf
 *  - econ: Οδηγός Σπουδών ΠΠΣ 2024-25 (unipi.gr)
 *  - fin:  bankfin.unipi.gr Οδηγός Σπουδών 25-26
 *  - stat: Οδηγός Σπουδών 2024-25 (unipi.gr/wp-content/uploads/2024/11/OS_24_25.pdf), with curriculum codes
 *  - bdt:  tex.unipi.gr odigos-spoudwn-25-26.pdf
 *  - nas:  maritime-unipi.gr Οδηγός Σπουδών 2024-25
 *  - des:  Οδηγός Σπουδών 2015-16 (the newer guides sit on des.unipi.gr, whose certificate has expired)
 *  - tou:  tourism.unipi.gr "Nth semester courses" pages, which link the eClass course codes directly
 *
 * `10` lists electives the guide offers in a winter/spring pool rather than a fixed semester.
 * Titles are matched after `normalizeCourseTitle`, so case, accents, years and "(Τμήμα Α-Λ)" noise do not matter.
 */
export interface DepartmentCurriculum {
  semesters: Record<number, string[]>;
  /** eClass course code or curriculum code -> semester (exact, wins over titles). */
  codes?: Record<string, number>;
  /** Curriculum codes that encode the semester, tried on the code, public code and title. */
  codeRule?: (text: string) => number | undefined;
}

