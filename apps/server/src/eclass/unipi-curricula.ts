const ROMAN = /^[iιvx]+$/;

/** Lowercase, accent-free, punctuation-free; Greek and Latin roman numerals unified ("ΙΙ" == "II"). */
export function normalizeCourseTitle(raw: string): string {
  return raw
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/ς/g, "σ")
    .replace(/&/g, " και ")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .split(" ")
    .filter(Boolean)
    .map((w) => (ROMAN.test(w) ? w.replace(/ι/g, "i") : w))
    .join(" ");
}

/** Strips what eClass adds around a course name: years, sections, codes, "(Ακαδ. έτος …)". */
function stripTitleNoise(raw: string): string {
  return (
    raw
      // Leading curriculum code: "ΝΑ107-…", "ΝΑ 409 …", "ΝΑΑΓΓ27-…"
      .replace(/^\s*(?:[A-ZΑ-Ω]{2,6}\s*){1,2}\d{1,3}[A-ZΑ-Ωα-ω]?(?:\s*[-–:.]\s*|\s+)(?=\S)/, " ")
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .toLowerCase()
      .replace(/\([^()]*\)|\[[^[\]]*\]/g, " ")
      .replace(/(?<!\d)(?:19|20)\d{2}(?:\s*[-–/]\s*(?:19|20)?\d{2})?(?!\d)/g, " ")
      .replace(/ακαδ[\p{L}.]*\s*ετο[σς]/gu, " ")
      .replace(/(?:χειμερινο|εαρινο)\s+εξαμηνο/g, " ")
      .replace(/τμημα\s+[α-ωa-z](?![\p{L}])['΄’]?/gu, " ")
      .replace(/(?<![\p{L}])[α-ω]\s*-\s*[α-ω](?![\p{L}])/gu, " ")
  );
}

interface CompiledCurriculum {
  exact: Map<string, number>;
  entries: Array<{ key: string; semester: number }>;
  codes: Map<string, number>;
}

const compiled = new Map<string, CompiledCurriculum>();

function compile(deptId: string): CompiledCurriculum | undefined {
  const cached = compiled.get(deptId);
  if (cached) return cached;
  const src = DEPARTMENT_CURRICULA[deptId];
  if (!src) return undefined;
  const exact = new Map<string, number>();
  const entries: CompiledCurriculum["entries"] = [];
  // Fixed semesters first, so a course listed both as core and as an elective keeps its semester
  const order = Object.keys(src.semesters)
    .map(Number)
    .sort((a, b) => (a === ELECTIVES_INDEX ? 1 : b === ELECTIVES_INDEX ? -1 : a - b));
  for (const sem of order) {
    for (const title of src.semesters[sem]) {
      const key = normalizeCourseTitle(title);
      if (!key || exact.has(key)) continue;
      exact.set(key, sem);
      entries.push({ key, semester: sem });
    }
  }
  const codes = new Map(Object.entries(src.codes ?? {}).map(([k, v]) => [k.toUpperCase().replace(/\s+/g, ""), v]));
  const result = { exact, entries, codes };
  compiled.set(deptId, result);
  return result;
}

/**
 * Semester (1..8, or ELECTIVES_INDEX) of a catalog course in the department's curriculum,
 * or undefined when the study guide does not list it.
 */
export function curriculumSemester(
  deptId: string | undefined,
  course: { code: string; publicCode?: string; title: string },
): number | undefined {
  if (!deptId) return undefined;
  const cur = compile(deptId);
  if (!cur) return undefined;

  for (const code of [course.code, course.publicCode]) {
    const hit = code ? cur.codes.get(code.toUpperCase().replace(/\s+/g, "")) : undefined;
    if (hit !== undefined) return hit;
  }
  const rule = DEPARTMENT_CURRICULA[deptId].codeRule;
  if (rule) {
    for (const text of [course.publicCode, course.code, course.title]) {
      const hit = text ? rule(text) : undefined;
      if (hit !== undefined) return hit;
    }
  }

  // Candidate names: the whole title, plus each side of "English / Ελληνικά" and "Τίτλος - Υπότιτλος"
  const cleaned = stripTitleNoise(course.title);
  const parts = [cleaned, ...cleaned.split(/\s+[/|]\s*|\s*[/|]\s+|\s+[-–—]{1,2}\s+/)];
  const candidates = [...new Set(parts.map(normalizeCourseTitle).filter((p) => p.length >= 3))];

  for (const c of candidates) {
    const hit = cur.exact.get(c);
    if (hit !== undefined) return hit;
  }

  // eClass titles often add a word ("… στη Ναυτιλία") or drop the tail ("Ναυτιλιακή Οικονομική" for
  // "… και Πολιτική"). Accept one unambiguous prefix match of at least two words either way.
  for (const c of candidates) {
    if (c.split(" ").length < 2) continue;
    const hits = new Set<number>();
    for (const e of cur.entries) {
      if (e.key.split(" ").length < 2) continue;
      if (c.startsWith(`${e.key} `) || e.key.startsWith(`${c} `)) hits.add(e.semester);
    }
    if (hits.size === 1) return [...hits][0];
  }
  return undefined;
}

/** Faculty folders of postgraduate programmes ("Μεταπτυχιακό", "ΠΜΣ …", "MSc …", "MBA …"). */
export function isPostgraduatePath(facultyPath: string[]): boolean {
  return facultyPath.some((p) =>
    /μεταπτυχ|(?<![\p{L}])Δ?Π\.?Μ\.?Σ(?![\p{L}])|(?<![\p{L}])M\.?Sc(?![\p{L}])|(?<![\p{L}])MBA(?![\p{L}])|master|postgrad/iu.test(p),
  );
}
